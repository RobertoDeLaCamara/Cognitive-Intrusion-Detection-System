#!/usr/bin/env bash
# Regenerate the hashed per-architecture lock files used by the Dockerfile.
# Needs uv (https://docs.astral.sh/uv/). Run after changing requirements.txt, requirements-dashboard.txt or the torch pin.
set -euo pipefail
cd "$(dirname "$0")/.."

TORCH_VERSION=2.6.0   # >= 2.6.0 fixes CVE-2025-32434
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

lock() {  # arch platform torch-requirement [extra uv args...]
    local arch=$1 platform=$2 torch=$3; shift 3
    { echo "-r $PWD/requirements.txt"; echo "$torch"; } > "$tmp/in-$arch.txt"
    {
        echo "# Hashed lock for TARGETARCH=$arch (python 3.11): requirements.txt + torch $TORCH_VERSION."
        echo "# Generated by scripts/lock_requirements.sh — do not edit by hand."
        # pip reads these from the file, so `pip install --require-hashes -r <lock>` finds the
        # torch+cpu local-version wheel that is not on PyPI.
        [ -n "${INDEX_HEADER:-}" ] && printf '%s\n' "$INDEX_HEADER"
        uv pip compile "$tmp/in-$arch.txt" --python-version 3.11 --python-platform "$platform" \
            --generate-hashes --no-header --no-annotate "$@"
    } > "requirements-lock-$arch.txt"
}

# amd64: explicit CPU build from the PyTorch index (smaller wheel); the rest from PyPI.
INDEX_HEADER=$'--index-url https://download.pytorch.org/whl/cpu\n--extra-index-url https://pypi.org/simple' \
lock amd64 x86_64-manylinux_2_28 "torch==${TORCH_VERSION}+cpu" \
    --index-url https://download.pytorch.org/whl/cpu --extra-index-url https://pypi.org/simple \
    --index-strategy unsafe-best-match
# arm64: the PyPI aarch64 wheel is CPU-only.
lock arm64 aarch64-manylinux_2_28 "torch==${TORCH_VERSION}"

# Split each lock into torch / numeric / rest parts so no Docker layer is huge (see split_lock.py).
python3 scripts/split_lock.py amd64 arm64

# Dashboard stage: requirements-dashboard.txt resolved on top of the base lock (-c), so the
# packages both share (pandas, requests, ...) keep the version already in the image. uv writes
# the hashes of every wheel of a version, so one file serves both architectures as long as the
# two resolutions agree; if they ever differ this fails and the file has to become per-arch.
dashboard_lock() {  # arch platform
    grep -vE '^--(extra-)?index-url' "requirements-lock-$1.txt" > "$tmp/constraints-$1.txt"
    uv pip compile requirements-dashboard.txt -c "$tmp/constraints-$1.txt" \
        --python-version 3.11 --python-platform "$2" \
        --generate-hashes --no-header --no-annotate > "$tmp/dashboard-$1.txt"
}
dashboard_lock amd64 x86_64-manylinux_2_28
dashboard_lock arm64 aarch64-manylinux_2_28
cmp "$tmp/dashboard-amd64.txt" "$tmp/dashboard-arm64.txt" \
    || { echo "dashboard lock differs between amd64 and arm64: make it per-arch" >&2; exit 1; }
{
    echo "# Hashed lock for the dashboard stage (python 3.11, amd64 and arm64): requirements-dashboard.txt"
    echo "# resolved on top of requirements-lock-<arch>.txt."
    echo "# Generated by scripts/lock_requirements.sh — do not edit by hand."
    cat "$tmp/dashboard-amd64.txt"
} > requirements-lock-dashboard.txt
