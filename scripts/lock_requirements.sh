#!/usr/bin/env bash
# Regenerate the hashed per-architecture lock files used by the Dockerfile.
# Needs uv (https://docs.astral.sh/uv/). Run after changing requirements.txt or the torch pin.
set -euo pipefail
cd "$(dirname "$0")/.."

TORCH_VERSION=2.6.0   # >= 2.6.0 fixes CVE-2025-32434
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

lock() {  # arch platform torch-requirement [extra uv args...]
    local arch=$1 platform=$2 torch=$3; shift 3
    { echo "-r $PWD/requirements.txt"; echo "$torch"; } > "$tmp/in-$arch.txt"
    {
        echo "# Hashed lock for TARGETARCH=$arch (python 3.11): requirements.txt + torch $TORCH_VERSION."
        echo "# Generated by scripts/lock_requirements.sh — do not edit by hand."
        uv pip compile "$tmp/in-$arch.txt" --python-version 3.11 --python-platform "$platform" \
            --generate-hashes --no-header --no-annotate "$@"
    } > "requirements-lock-$arch.txt"
}

# amd64: explicit CPU build from the PyTorch index (smaller wheel); the rest from PyPI.
lock amd64 x86_64-manylinux_2_28 "torch==${TORCH_VERSION}+cpu" \
    --index-url https://download.pytorch.org/whl/cpu --extra-index-url https://pypi.org/simple \
    --index-strategy unsafe-best-match
# arm64: the PyPI aarch64 wheel is CPU-only.
lock arm64 aarch64-manylinux_2_28 "torch==${TORCH_VERSION}"
