"""Integrity check for pickle-based model artifacts (joblib / sklearn pickles).

Unpickling runs arbitrary code, so a tampered file in MODELS_DIR is code execution
inside the API/detector process. Before any joblib load the file's SHA-256 is checked
against a manifest in sha256sum format (`<hex>  <path relative to MODELS_DIR>`),
generated by `python scripts/model_manifest.py write`.

MODEL_INTEGRITY_MODE:
  auto     (default) enforce when the manifest file exists, warn once when it does not
  enforce  the manifest is required; a missing manifest, missing entry or mismatch refuses the load
  off      no checks
"""

import hashlib
import hmac
import logging
import os

import joblib

from .config import MODELS_DIR, MODEL_INTEGRITY_MODE, MODEL_MANIFEST_PATH

logger = logging.getLogger(__name__)

_warned_no_manifest = False


class ModelIntegrityError(RuntimeError):
    """A model artifact is not covered by the manifest or does not match its hash."""


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _rel(path: str, models_dir: str) -> str:
    return os.path.relpath(os.path.realpath(path), os.path.realpath(models_dir)).replace(os.sep, "/")


def read_manifest(manifest_path: str) -> dict:
    entries = {}
    with open(manifest_path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            digest, _, name = line.partition("  ")
            entries[name.strip().lstrip("*")] = digest.lower()
    return entries


def verify(path: str, *, mode: str = None, models_dir: str = None, manifest_path: str = None) -> None:
    """Raise ModelIntegrityError unless `path` is allowed to be loaded under the current mode."""
    global _warned_no_manifest
    mode = (mode or MODEL_INTEGRITY_MODE).lower()
    if mode == "off":
        return
    models_dir = models_dir or MODELS_DIR
    manifest_path = manifest_path or MODEL_MANIFEST_PATH

    if not os.path.exists(manifest_path):
        if mode == "enforce":
            raise ModelIntegrityError(f"integrity manifest {manifest_path} not found; refusing to load {path}")
        if not _warned_no_manifest:
            _warned_no_manifest = True
            logger.warning(
                "No model manifest at %s: pickle artifacts are loaded unverified. "
                "Generate one with `python scripts/model_manifest.py write`.", manifest_path)
        return

    name = _rel(path, models_dir)
    expected = read_manifest(manifest_path).get(name)
    if expected is None:
        raise ModelIntegrityError(f"{name} is not listed in {manifest_path}; refusing to load it")
    if not hmac.compare_digest(sha256_file(path), expected):
        raise ModelIntegrityError(f"{name} does not match its SHA-256 in {manifest_path}; refusing to load it")


def load_joblib(path: str, **kwargs):
    """joblib.load after verifying the file against the manifest."""
    verify(path, **kwargs)
    return joblib.load(path)
